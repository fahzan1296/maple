//! SIXEL passthrough helpers (port of `l/src/render/sixel.ts`).
//! Reference: `l/src/render/sixel.ts`.
//!
//! Terminals that support SIXEL receive the raw control sequence unchanged;
//! everywhere else the sequence is stripped by the sanitizer. Passthrough is
//! opt-in through two environment gates.

use regex::Regex;
use std::sync::LazyLock;
const SIXEL_END_SEQUENCE: &str = "\x1b\\";
const SIXEL_END_BELL: &str = "\x07";
const SIXEL_PLACEHOLDER_PREFIX: &str = "__OMP_SIXEL_SEQUENCE_";

static SIXEL_START_REGEX: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\x1bP(?:[0-9;]*)q").expect("valid regex"));
static SIXEL_SEQUENCE_REGEX: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"\x1bP(?:[0-9;]*)q[\s\S]*?(?:\x1b\\|\x07)").expect("valid regex")
});
static SIXEL_PLACEHOLDER_REGEX: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"__OMP_SIXEL_SEQUENCE_(\d+)__").expect("valid regex"));

/// Parse a maple-tui style boolean flag (`1`, `true`, `yes`, `on`).
fn flag(name: &str) -> bool {
    match crate::env_lookup(name).and_then(|value| value.into_string().ok()) {
        Some(value) => {
            let value = value.trim().to_ascii_lowercase();
            matches!(value.as_str(), "1" | "true" | "yes" | "on")
        }
        None => false,
    }
}

/// Whether SIXEL passthrough is explicitly enabled.
///
/// Both gates must be enabled to preserve SIXEL control sequences:
/// `MAPLE_FORCE_IMAGE_PROTOCOL=sixel` and `MAPLE_ALLOW_SIXEL_PASSTHROUGH=1`.
pub fn is_sixel_passthrough_enabled() -> bool {
    let forced = crate::env_lookup("MAPLE_FORCE_IMAGE_PROTOCOL")
        .and_then(|value| value.into_string().ok())
        .map(|value| value.trim().eq_ignore_ascii_case("sixel"))
        .unwrap_or(false);
    forced && flag("MAPLE_ALLOW_SIXEL_PASSTHROUGH")
}

/// Whether the text contains a SIXEL start sequence.
pub fn contains_sixel_sequence(text: &str) -> bool {
    SIXEL_START_REGEX.is_match(text)
}

/// Whether the line contains a SIXEL start sequence.
pub fn is_sixel_line(line: &str) -> bool {
    contains_sixel_sequence(line)
}

/// Mask indicating which lines belong to a SIXEL sequence block.
///
/// Supports multi-line SIXEL payloads generated by libsixel.
pub fn get_sixel_line_mask(lines: &[String]) -> Vec<bool> {
    let mut in_sequence = false;
    lines
        .iter()
        .map(|line| {
            if contains_sixel_sequence(line) {
                in_sequence = true;
            }
            let is_sixel_line = in_sequence;
            if in_sequence && (line.contains(SIXEL_END_SEQUENCE) || line.contains(SIXEL_END_BELL)) {
                in_sequence = false;
            }
            is_sixel_line
        })
        .collect()
}

/// Sanitize `text` while preserving embedded SIXEL sequences when `enabled`.
pub fn sanitize_with_sixel_passthrough<F>(text: &str, enabled: bool, sanitize: F) -> String
where
    F: FnOnce(&str) -> String,
{
    if !enabled || !contains_sixel_sequence(text) {
        return sanitize(text);
    }
    let mut preserved: Vec<String> = Vec::new();
    let tokenized = SIXEL_SEQUENCE_REGEX.replace_all(text, |captures: &regex::Captures| {
        let token = format!("{SIXEL_PLACEHOLDER_PREFIX}{}__", preserved.len());
        preserved.push(captures[0].to_string());
        token
    });
    let sanitized = sanitize(&tokenized);
    SIXEL_PLACEHOLDER_REGEX
        .replace_all(&sanitized, |captures: &regex::Captures| {
            let index: usize = captures[1].parse().unwrap_or(usize::MAX);
            preserved.get(index).cloned().unwrap_or_default()
        })
        .into_owned()
}

/// XTSMGRAPHICS query plus a DA1 sentinel, so a terminal that answers only
/// DA1 resolves as unsupported.
pub const XTSMGRAPHICS_QUERY: &str = "\x1b[?2;1;0S\x1b[c";

/// Whether `sequence` is an XTSMGRAPHICS reply (`CSI ? 2 ; … S`).
pub fn is_xtsmgraphics_reply(sequence: &str) -> bool {
    sequence.starts_with("\x1b[?2;") && sequence.ends_with('S')
}

/// Parse a successful XTSMGRAPHICS reply into the terminal's maximum SIXEL
/// geometry in pixels. Non-zero status replies are unsupported.
pub fn parse_xtsmgraphics_reply(sequence: &str) -> Option<(u32, u32)> {
    if !is_xtsmgraphics_reply(sequence) {
        return None;
    }
    let body = sequence.strip_prefix("\x1b[?2;")?.strip_suffix('S')?;
    let mut parts = body.split(';');
    let status: u32 = parts.next()?.parse().ok()?;
    if status != 0 {
        return None;
    }
    let width = parts.next()?.parse().ok()?;
    let height = parts.next()?.parse().ok()?;
    Some((width, height))
}

/// SIXEL capability probe state.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct SixelProbe {
    max: Option<(u32, u32)>,
    da1_seen: bool,
}

impl SixelProbe {
    pub fn new() -> Self {
        Self::default()
    }

    /// Bytes to write at startup.
    #[must_use]
    pub fn begin() -> &'static str {
        XTSMGRAPHICS_QUERY
    }

    /// Consume one raw stdin sequence. Returns whether it belonged to the
    /// probe (an XTSMGRAPHICS reply or the DA1 sentinel).
    pub fn feed(&mut self, sequence: &str) -> bool {
        if is_xtsmgraphics_reply(sequence) {
            self.max = parse_xtsmgraphics_reply(sequence);
            return true;
        }
        if crate::terminal::program_status::is_da1_response(sequence) {
            self.da1_seen = true;
            return true;
        }
        false
    }

    /// Whether the terminal reported a maximum SIXEL geometry.
    #[must_use]
    pub fn supported(&self) -> bool {
        self.max.is_some()
    }

    /// The reported maximum geometry, if any.
    #[must_use]
    pub fn max(&self) -> Option<(u32, u32)> {
        self.max
    }

    /// Whether a DA1 sentinel arrived.
    #[must_use]
    pub fn da1_seen(&self) -> bool {
        self.da1_seen
    }

    /// Invalidate support (terminal restart).
    pub fn stop(&mut self) {
        self.max = None;
        self.da1_seen = false;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_sixel_starts() {
        assert!(contains_sixel_sequence("\x1bPq#0;2;0;0;0data\x1b\\"));
        assert!(contains_sixel_sequence("\x1bP1;2q"));
        assert!(!contains_sixel_sequence("\x1b[31mred"));
    }

    #[test]
    fn mask_covers_multiline_payload() {
        let lines = vec![
            "before".to_string(),
            "\x1bPq#0;2;0;0;0".to_string(),
            "payload".to_string(),
            "\x1b\\".to_string(),
            "after".to_string(),
        ];
        assert_eq!(
            get_sixel_line_mask(&lines),
            vec![false, true, true, true, false]
        );
    }

    #[test]
    fn mask_handles_bell_terminator() {
        let lines = vec!["\x1bPqdata\x07".to_string(), "after".to_string()];
        assert_eq!(get_sixel_line_mask(&lines), vec![true, false]);
    }

    #[test]
    fn sanitizes_without_passthrough() {
        let out = sanitize_with_sixel_passthrough("a\x1bPqdata\x1b\\b", false, |text| {
            text.replace('\x1b', "")
        });
        assert_eq!(out, "aPqdata\\b");
    }

    #[test]
    fn preserves_sequences_when_enabled() {
        let out = sanitize_with_sixel_passthrough("a\x1bPqdata\x1b\\b", true, |text| {
            text.replace("a", "A").replace("b", "B")
        });
        assert_eq!(out, "A\x1bPqdata\x1b\\B");
    }

    #[test]
    fn preserves_multiple_sequences_in_order() {
        let out = sanitize_with_sixel_passthrough(
            "\x1bPq1\x1b\\x\x1bPq2\x1b\\",
            true,
            |text| text.to_string(),
        );
        assert_eq!(out, "\x1bPq1\x1b\\x\x1bPq2\x1b\\");
    }
}
